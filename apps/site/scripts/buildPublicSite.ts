/** MIG-0509: build-only public snapshot → Astro static assets pipeline.
 * Never deploys, writes D1/R2 or accesses production Cloudflare configuration.
 * Credentials are used only during snapshot generation and are removed from child process env.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawn} from "node:child_process";
import {fileURLToPath} from "node:url";
import {main as produceMain} from "./produceSnapshots.ts";

const REPO=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../../..");
const SNAPSHOT_DIR_PREFIX="flamenode-public-build-";
const USAGE="usage: buildPublicSite.ts (--sqlite FILE|--sql-dump FILE|--d1-api) [--trending-file FILE|--trending-r2] [--now SEC] [--generation ID]";
export interface BuildCommand {
  command:string; args:string[]; env:NodeJS.ProcessEnv;
}
export interface BuildReport {
  keys:number; bytes:number; d1Statements:number; elapsedMs:number;
  buildElapsedMs:number; generation:string; snapshotDir:string;
}
export function buildPublicSiteArgs(argv:readonly string[], env:Record<string,string|undefined>=process.env):string[] {
  if(argv.includes("--out"))throw new Error("buildPublicSite manages its own temporary snapshot directory");
  const local=argv.includes("--sqlite")||argv.includes("--sql-dump");
  const generationIndex=argv.indexOf("--generation");
  const generation=generationIndex<0?(env.WORKERS_CI_COMMIT_SHA || (local?"local-fixture":undefined)):undefined;
  if(generationIndex<0&&!generation)throw new Error(USAGE);
  return generationIndex<0?[...argv,"--generation",generation!]:[...argv];
}
export function safeBuildEnv(original:NodeJS.ProcessEnv,snapshotDir:string,generation:string):NodeJS.ProcessEnv {
  const env={...original,
    FLAMENODE_SNAPSHOT_DIR:snapshotDir,
    FLAMENODE_SNAPSHOT_MANIFEST_FILE:path.join(snapshotDir,"manifest.json"),
    FLAMENODE_SNAPSHOT_GENERATION:generation,
  };
  const rules=path.join(snapshotDir,"rules-current.json");
  if(fs.existsSync(rules))env.FLAMENODE_RULES_SNAPSHOT_FILE=rules;
  for(const key of ["FLAMENODE_D1_READ_TOKEN","FLAMENODE_R2_READ_TOKEN",
    "CLOUDFLARE_API_TOKEN","CF_API_TOKEN","CLOUDFLARE_API_KEY"])delete env[key];
  return env;
}
export async function runBuildCommand({command,args,env}:BuildCommand):Promise<void> {
  await new Promise<void>((resolve,reject)=>{
    const child=spawn(command,args,{cwd:REPO,env,stdio:"inherit",shell:false});
    child.on("error",()=>reject(new Error("build command failed to launch")));
    child.on("close",code=>code===0?resolve():reject(new Error("build command failed with exit="+code)));
  });
}
export async function buildPublicSite(
  argv:string[],
  options:{env?:NodeJS.ProcessEnv;fetchFn?:typeof fetch;run?:typeof runBuildCommand}={},
):Promise<BuildReport>{
  const started=performance.now();
  const env=options.env??process.env;
  const args=buildPublicSiteArgs(argv,env);
  const snapshotDir=fs.mkdtempSync(path.join(os.tmpdir(),SNAPSHOT_DIR_PREFIX));
  try{
    const result=await produceMain([...args,"--out",snapshotDir],{env,fetchFn:options.fetchFn,quiet:true});
    // Required content includes trending. Missing R2 object is not replaced with arbitrary fake data.
    if(result.report.trending==="missing")throw new Error("public build aborted: trending snapshot is unavailable");
    const childEnv=safeBuildEnv(env,snapshotDir,result.manifest.generation);
    const run=options.run??runBuildCommand;
    const npm=process.platform==="win32"?"npm.cmd":"npm";
    await run({command:npm,args:["run","build","--workspace=@flamenode/site"],env:childEnv});
    await run({command:process.execPath,args:["scripts/check-public-site-build-budget.mjs"],env:childEnv});
    const report={keys:result.report.keys,bytes:result.report.bytes,d1Statements:result.report.d1Statements,
      elapsedMs:Math.round(performance.now()-started),
      buildElapsedMs:Math.round(performance.now()-started-result.report.elapsedMs),
      generation:result.report.generation,snapshotDir};
    console.log(JSON.stringify({buildPublicSite:report}));
    return report;
  }catch(error){
    // No secrets in the errors generated by the two build-only readers.
    // Preserve the files for diagnosis; never dump token-bearing env or HTTP headers.
    throw error;
  }
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===path.resolve(process.argv[1])){
  buildPublicSite(process.argv.slice(2)).catch(error=>{
    console.error(error instanceof Error?error.message:"public build failed");process.exitCode=1;
  });
}
