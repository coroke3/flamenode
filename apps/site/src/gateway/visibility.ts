/**
 * Visibility and route evaluation for the public gateway (MIG-0405 / Recipe R-GATEWAY / Runtime S1).
 * Evaluates visibility fences and route resolution in O(1) time without D1 queries.
 */
import {
  lookupRoute,
  type RouteEntityKind,
  type RouteManifest,
  type RouteResolution,
} from "../lib/routeMap.ts";

export type GatewayRevocationChecker = (
  kind: RouteEntityKind,
  id: string,
) => boolean | Promise<boolean>;

export type GatewayDecision =
  | Readonly<{
      action: "serve";
      kind: RouteEntityKind;
      id: string;
      canonicalPath: string;
      assetPath: string;
    }>
  | Readonly<{
      action: "redirect";
      targetPath: string;
      status: 301 | 302 | 307 | 308;
      reason: "alias" | "legacy";
    }>
  | Readonly<{
      action: "deny";
      status: 404;
      reason: "not_found" | "revoked" | "traversal" | "private";
      headers: Readonly<Record<string, string>>;
    }>
  | Readonly<{
      action: "bypass";
      reason: "auth_protected";
    }>
  | Readonly<{
      action: "unavailable";
      status: 503;
      reason: "manifest_missing" | "manifest_corrupt";
    }>;

const DENY_HEADERS: Readonly<Record<string, string>> = Object.freeze({
  "X-Robots-Tag": "noindex, nofollow",
  "Cache-Control": "no-store, private",
});

function hasPathTraversal(path: string): boolean {
  return path.includes("..") || path.includes("\\") || /%2f|%2e|%5c/i.test(path);
}

function computeAssetPath(kind: RouteEntityKind, id: string): string {
  // Public HTML pre-generated by Astro SSG / R2
  if (kind === "video") return `/${id}/index.html`;
  return `/${kind}/${id}/index.html`;
}

/**
 * Pure visibility and route evaluation function.
 * Guarantee: Fails closed on any ambiguity, corruption, or revocation.
 */
export async function evaluateVisibility(
  path: string,
  manifest: RouteManifest | null | undefined,
  isRevoked?: GatewayRevocationChecker,
): Promise<GatewayDecision> {
  // 1. Auth protection: Never intercept Auth.js endpoints
  if (path === "/api/auth" || path.startsWith("/api/auth/")) {
    return { action: "bypass", reason: "auth_protected" };
  }

  // 2. Traversal rejection: Fail-closed with 404
  if (hasPathTraversal(path)) {
    return {
      action: "deny",
      status: 404,
      reason: "traversal",
      headers: DENY_HEADERS,
    };
  }

  // 3. Manifest integrity: If missing or corrupt, fail-closed with 503
  if (!manifest || typeof manifest !== "object" || manifest.schemaVersion !== 1) {
    return {
      action: "unavailable",
      status: 503,
      reason: "manifest_missing",
    };
  }

  // 4. Route resolution lookup (O(1) dictionary lookup)
  const resolution: RouteResolution | null = lookupRoute(manifest, path);
  if (!resolution) {
    return {
      action: "deny",
      status: 404,
      reason: "not_found",
      headers: DENY_HEADERS,
    };
  }

  // 5. Handle redirects (alias or legacy)
  if (resolution.type === "redirect") {
    return {
      action: "redirect",
      targetPath: resolution.targetPath,
      status: resolution.status,
      reason: resolution.reason,
    };
  }

  // 6. Handle canonical routes and revocation fence
  if (resolution.type === "canonical") {
    if (isRevoked) {
      const revoked = await isRevoked(resolution.kind, resolution.id);
      if (revoked) {
        return {
          action: "deny",
          status: 404,
          reason: "revoked",
          headers: DENY_HEADERS,
        };
      }
    }

    return {
      action: "serve",
      kind: resolution.kind,
      id: resolution.id,
      canonicalPath: resolution.canonicalPath,
      assetPath: computeAssetPath(resolution.kind, resolution.id),
    };
  }

  // Catch-all fail-closed
  return {
    action: "deny",
    status: 404,
    reason: "private",
    headers: DENY_HEADERS,
  };
}
